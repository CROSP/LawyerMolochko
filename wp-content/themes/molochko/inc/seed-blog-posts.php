$created = 0;
foreach ( $articles as $i => $article ) {
	$post_date = date( 'Y-m-d H:i:s', strtotime( $article['date'] ) );
	$post_id   = wp_insert_post( array(
		'post_author'   => $user_id,
		'post_title'    => $article['title'],
		'post_content'  => $article['content'],
		'post_excerpt'  => $article['excerpt'],
		'post_status'   => 'publish',
		'post_type'     => 'post',
		'post_date'     => $post_date,
		'post_date_gmt' => get_gmt_from_date( $post_date ),
	) );
	if ( $post_id && ! is_wp_error( $post_id ) ) {
		$created++;
		if ( ! empty( $article['img'] ) ) {
			$attachment_id = media_sideload_image( $article['img'], $post_id, $article['title'], 'id' );
			if ( $attachment_id && ! is_wp_error( $attachment_id ) ) {
				set_post_thumbnail( $post_id, $attachment_id );
			}
		}
		if ( class_exists( 'WP_CLI' ) ) {
			WP_CLI::log( "Created post: {$article['title']}" );
		}
	}
}

if ( class_exists( 'WP_CLI' ) ) {
	WP_CLI::success( "Done: deleted " . count( $existing ) . " old post(s), created {$created} new blog article(s)." );
} else {
	echo "Done: deleted " . count( $existing ) . " old post(s), created {$created} new blog article(s).\n";
}

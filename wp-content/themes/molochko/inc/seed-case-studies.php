// Allow external image downloads (Pexels, etc.) to follow redirects and identify as browser.
add_filter( 'http_request_args', function ( $args, $url ) {
	if ( strpos( $url, 'http' ) === 0 && ( strpos( $url, '.jpg' ) !== false || strpos( $url, '.jpeg' ) !== false || strpos( $url, '.png' ) !== false || strpos( $url, 'pexels.com' ) !== false || strpos( $url, 'unsplash' ) !== false || strpos( $url, 'powerlegal' ) !== false ) ) {
		$args['redirection'] = 5;
		$args['user-agent']  = 'Mozilla/5.0 (compatible; WordPress/' . get_bloginfo( 'version' ) . '; +' . get_bloginfo( 'url' ) . ')';
	}
	return $args;
}, 10, 2 );

$created = 0;

foreach ( $items as $item ) {
	$title   = $item['title'];
	$excerpt = isset( $item['excerpt'] ) ? $item['excerpt'] : '';
	$content = isset( $item['content'] ) ? $item['content'] : '';
	$cat     = $item['cat'];
	$img     = isset( $item['img'] ) ? $item['img'] : '';

	$exists = get_posts( array(
		'post_type'      => 'molochko-case-study',
		'title'          => $title,
		'posts_per_page' => 1,
		'fields'         => 'ids',
	) );
	if ( ! empty( $exists ) ) {
		continue;
	}

	$post_id = wp_insert_post( array(
		'post_type'    => 'molochko-case-study',
		'post_title'   => $title,
		'post_content' => $content,
		'post_excerpt' => $excerpt,
		'post_status'  => 'publish',
	) );
	if ( ! $post_id ) {
		continue;
	}

	$term = term_exists( $cat, 'case_study_category' );
	if ( 0 === $term || null === $term ) {
		// Use Latin slug for URLs (Cyr-To-Lat plugin or fallback to name-based slug).
		$slug = null;
		if ( function_exists( 'cyr_to_lat' ) && is_object( cyr_to_lat() ) && method_exists( cyr_to_lat(), 'transliterate' ) ) {
			$slug = sanitize_title( cyr_to_lat()->transliterate( $cat ) );
		}
		$args = $slug ? array( 'slug' => $slug ) : array();
		$term = wp_insert_term( $cat, 'case_study_category', $args );
	}
	if ( ! is_wp_error( $term ) ) {
		$term_id = is_array( $term ) ? $term['term_id'] : $term['term_id'];
		wp_set_post_terms( $post_id, array( $term_id ), 'case_study_category', false );
	}

	if ( ! empty( $img ) ) {
		$attachment_id = media_sideload_image( $img, $post_id, $title, 'id' );
		if ( is_wp_error( $attachment_id ) ) {
			// Fallback: use any existing image from media library so cards show an image.
			$fallback = get_posts( array(
				'post_type'      => 'attachment',
				'post_mime_type' => 'image',
				'posts_per_page' => 1,
				'fields'         => 'ids',
				'post_status'    => 'inherit',
			) );
			if ( ! empty( $fallback ) ) {
				$attachment_id = (int) $fallback[0];
			}
		}
		if ( ! empty( $attachment_id ) && ! is_wp_error( $attachment_id ) ) {
			set_post_thumbnail( $post_id, $attachment_id );
		}
	}

	$created++;
	if ( class_exists( 'WP_CLI' ) ) {
		WP_CLI::log( "Created case study: {$title}" );
	}
}

if ( class_exists( 'WP_CLI' ) ) {
	WP_CLI::success( "Created {$created} case study posts (Ukrainian, with descriptions)." );
}
